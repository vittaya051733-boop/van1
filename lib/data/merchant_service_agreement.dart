หมวดที่ 1 : คำนิยาม วัตถุประสงค์ และขอบเขต
────────────────────────────────────────
1.1 “แพลตฟอร์ม” หมายถึง ระบบ แว๊นตลาด รวมถึงแอปพลิเคชัน ระบบหลังบ้าน และช่องทางที่ผู้ให้บริการแพลตฟอร์มเปิดให้ร้านค้าใช้งาน
1.2 “สินค้าและบริการ” หมายถึง สินค้า อาหาร บริการ หรือรายการที่ร้านค้าลงขายผ่านแพลตฟอร์ม ไม่ว่าประเภทตลาด ร้านค้า ร้านอาหาร ร้านขายยา หรืออื่นใดที่อนุมัติแล้ว
1.3 วัตถุประสงค์ของสัญญานี้ คือ กำหนดสิทธิ หน้าที่ และความรับผิดชอบระหว่างผู้ให้บริการแพลตฟอร์มกับร้านค้า ในการให้บริการลงขาย รับออเดอร์ ชำระเงิน และบริหารจัดการร้านผ่านแพลตฟอร์ม
1.4 สัญญานี้ใช้กับร้านค้าทุกประเภทที่ลงทะเบียนผ่านระบบ โดยข้อเฉพาะด้านอาหารหรือยาจะใช้เพิ่มเติมตามหมวดที่ 5 เมื่อร้านค้าจำหน่ายสินค้าประเภทนั้น

────────────────────────────────────────
หมวดที่ 2 : สิทธิและหน้าที่ของผู้ให้บริการแพลตฟอร์ม
────────────────────────────────────────
2.1 จัดให้มีระบบลงทะเบียนร้าน ลงขายสินค้า รับออเดอร์ แจ้งเตือน และช่องทางติดต่อแอดมิน
2.2 พิจารณาอนุมัติหรือไม่อนุมัติร้านค้า ตามเอกสาร ข้อมูล และนโยบายของแพลตฟอร์ม
2.3 กำหนดและปรับปรุงนโยบายค่าธรรมเนียม การชำระเงิน การโอนรายได้ และเงื่อนไขโปรโมชัน โดยแจ้งผ่านแพลตฟอร์มหรือช่องทางที่เหมาะสม
2.4 มีสิทธิตรวจสอบ สอบถาม หรือขอเอกสารเพิ่มเติมจากร้านค้า เพื่อรักษามาตรฐาน ความปลอดภัย และความน่าเชื่อถือของแพลตฟอร์ม
2.5 ไม่รับประกันว่าร้านค้าจะมีรายได้หรือปริมาณออเดอร์ในระดับใด แต่จะดำเนินการให้ระบบทำงานตามมาตรฐานที่สมเหตุสมผล

────────────────────────────────────────
หมวดที่ 3 : สิทธิและหน้าที่ของร้านค้า
────────────────────────────────────────
3.1 ให้ข้อมูลร้าน ที่อยู่ บัญชีธนาคาร เอกสารยืนยันตัวตน และข้อมูลติดต่อ ที่ถูกต้อง ครบถ้วน และเป็นปัจจุบัน
3.2 รักษาความปลอดภัยบัญชีผู้ใช้ รหัสผ่าน และอุปกรณ์ที่ใช้เข้าระบบ ไม่มอบหมายให้บุคคลอื่นใช้แทนโดยไม่ได้รับอนุญาต
3.3 ปฏิบัติตามกฎหมายไทย ใบอนุญาตที่เกี่ยวข้อง (เช่น ใบอนุญาตขายอาหาร ใบอนุญาตขายยา หรือใบอนุญาตประกอบการอื่น) และนโยบายของแพลตฟอร์ม
3.4 ไม่กระทำการฉ้อโกง ปลอมแปลงข้อมูล ขายสินค้าผิดกฎหมาย หรือกระทำการที่ก่อให้เกิดความเสียหายต่อลูกค้า ผู้ให้บริการแพลตฟอร์ม หรือบุคคลที่สาม
3.5 ให้ความร่วมมือในการตรวจสอบข้อร้องเรียน การสอบสวน และการแก้ไขปัญหาที่เกี่ยวข้องกับร้านค้า

────────────────────────────────────────
หมวดที่ 4 : การลงทะเบียน เอกสาร และการอนุมัติร้าน
────────────────────────────────────────
4.1 ร้านค้าต้องลงทะเบียนตามขั้นตอนที่กำหนด รวมถึงการยอมรับสัญญานี้ ลงลายมือชื่อ และส่งเอกสารยืนยันตัวตนตามที่ระบบร้องขอ
4.2 ร้านค้าจะเปิดขายได้เมื่อได้รับการอนุมัติจากผู้ให้บริการแพลตฟอร์มเท่านั้น
4.3 หากข้อมูลเปลี่ยนแปลง (ชื่อร้าน ที่อยู่ บัญชีธนาคาร ผู้มีอำนาจ ใบอนุญาต) ร้านค้าต้องอัปเดตในระบบภายในระยะเวลาที่สมเหตุสมผล
4.4 การให้ข้อมูลเท็จ เอกสารปลอม หรือการปกปิดข้อมูลสำคัญ ถือเป็นเหตุระงับหรือยกเลิกบัญชีได้ทันที

────────────────────────────────────────
หมวดที่ 5 : มาตรฐานสินค้า บริการ และความปลอดภัย
────────────────────────────────────────
5.1 ร้านค้ารับรองว่าสินค้าและบริการที่จำหน่าย ถูกต้องตามกฎหมาย ตรงตามที่แสดงในแพลตฟอร์ม และไม่เป็นอันตรายต่อผู้บริโภค
5.2 สำหรับอาหารและเครื่องดื่ม ร้านค้าต้องปฏิบัติตามหลักสุขาภิบาลอาหาร ใช้วัตถุดิบที่มีคุณภาพ ไม่หมดอายุ และไม่ใช้สารต้องห้ามตามที่ อย. กำหนด
5.3 สำหรับยาและผลิตภัณฑ์ที่เกี่ยวข้อง ร้านค้าต้องมีใบอนุญาตที่ถูกต้อง จัดเก็บตามมาตรฐาน และไม่จำหน่ายยาที่ควบคุมโดยไม่ได้รับอนุญาต
5.4 ร้านค้าต้องจัดเก็บ ผลิต บรรจุ และส่งมอบสินค้าในสภาพที่เหมาะสม และพร้อมให้ตรวจสอบเมื่อมีเหตุอันสมควร
5.5 ร้านค้าต้องแจ้งส่วนผสม สารก่อภูมิแพ้ หรือข้อควรระวังที่สำคัญต่อลูกค้า เมื่อเกี่ยวข้องกับประเภทสินค้า

────────────────────────────────────────
หมวดที่ 6 : การลงขาย ราคา โปรโมชัน และการแสดงข้อมูล
────────────────────────────────────────
6.1 ร้านค้ารับผิดชอบเนื้อหา รูปภาพ วิดีโอ ราคา ส่วนลด และรายละเอียดสินค้าที่ลงขายทั้งหมด
6.2 ห้ามแสดงข้อมูลที่เป็นเท็จ ก่อกวน ละเมิดลิขสิทธิ์ หรือละเมิดสิทธิบุคคลของผู้อื่น
6.3 ราคาที่แสดงต้องเป็นราคาที่เรียกเก็บจากลูกค้าจริง ไม่มีค่าใช้จ่ายแอบแฝงที่ไม่ได้แจ้ง
6.4 ผู้ให้บริการแพลตฟอร์มมีสิทธิแก้ไข ซ่อน หรือถอดสินค้าที่ละเมิดนโยบาย โดยไม่ต้องแจ้งล่วงหน้าในกรณีเร่งด่วนเพื่อความปลอดภัย

────────────────────────────────────────
หมวดที่ 7 : การรับออเดอร์ การจัดเตรียม และการส่งมอบ
────────────────────────────────────────
7.1 ร้านค้าต้องรับออเดอร์ จัดเตรียมสินค้า และอัปเดตสถานะในระบบ ตามเวลาที่กำหนดหรือตามที่ตกลงกับลูกค้า
7.2 หากไม่สามารถปฏิบัติตามออเดอร์ได้ ร้านค้าต้องแจ้งและดำเนินการยกเลิกหรือแก้ไขอย่างเหมาะสม โดยไม่ก่อให้ลูกค้าเสียหายโดยไม่จำเป็น
7.3 ร้านค้าต้องส่งมอบสินค้าให้ลูกค้าหรือผู้ให้บริการขนส่ง/ไรเดอร์ (ตามระบบ) ในสภาพสมบูรณ์และตรงตามรายการ
7.4 ความล่าช้า สินค้าผิด สินค้าชำรุด หรือการไม่ดำเนินการตามออเดอร์ เป็นความรับผิดชอบของร้านค้า เว้นแต่พิสูจน์ได้ว่าเกิดจากเหตุสุดวิสัย

────────────────────────────────────────
หมวดที่ 8 : การชำระเงิน รายได้ ค่าธรรมเนียม และการโอนเงิน
────────────────────────────────────────
8.1 การชำระเงินของลูกค้าดำเนินการผ่านช่องทางที่แพลตฟอร์มรองรับ (เช่น โอนเงิน สลิป QR หรือวิธีอื่นที่กำหนด)
8.2 รายได้สุทธิของร้านค้าคำนวณตามนโยบายที่ผู้ให้บริการแพลตฟอร์มกำหนด หักค่าธรรมเนียมแพลตฟอร์ม ค่าขนส่ง หรือรายการอื่นที่แจ้งไว้
8.3 การโอนเงินให้ร้านค้าเป็นไปตามรอบและเงื่อนไขที่แสดงในระบบ (เช่น กระเป๋าเงินร้าน การถอน หรือการเคลียร์ยอด)
8.4 ร้านค้าต้องตรวจสอบยอดรายได้และแจ้งข้อโต้แย้งภายในระยะเวลาที่กำหนด มิฉะนั้นถือว่ายอดถูกต้อง

────────────────────────────────────────
หมวดที่ 9 : ภาษี ใบกำกับ และเอกสารทางการเงิน
────────────────────────────────────────
9.1 ร้านค้ามีหน้าที่ปฏิบัติตามกฎหมายภาษีอากรที่เกี่ยวข้องกับการประกอบการของตนเอง
9.2 หากกฎหมายกำหนดให้ออกใบกำกับภาษี ใบเสร็จ หรือเอกสารอื่น ร้านค้าต้องดำเนินการให้ลูกค้าตามที่เหมาะสม
9.3 ร้านค้าต้องให้ข้อมูลบัญชีธนาคารที่ถูกต้องสำหรับรับโอนเงิน และรับผิดชอบความเสียหายจากข้อมูลบัญชีผิด

────────────────────────────────────────
หมวดที่ 10 : ความรับผิด การชดเชย และความเสียหาย
────────────────────────────────────────
10.1 หากสินค้าหรือบริการของร้านค้าก่อให้เกิดอันตราย การเจ็บป่วย การแพ้ หรือความเสียหายแก่ลูกค้า ร้านค้าต้องรับผิดชอบและชดเชยค่าเสียหายที่เกิดขึ้นจริง
10.2 ร้านค้าต้องชดใช้ค่าเสียหายแก่ผู้ให้บริการแพลตฟอร์ม หากร้านค้ากระทำผิดสัญญา กฎหมาย หรือก่อให้แพลตฟอร์มถูกเรียกร้องจากบุคคลที่สาม (รวมค่าชดเชยลูกค้า ค่าตรวจสอบ ค่าทนายความตามที่เกิดขึ้นจริง)
10.3 ในกรณีร้องเรียนซ้ำ อาหารหรือสินค้าไม่ปลอดภัย หรือการกระทำที่ร้ายแรง ผู้ให้บริการแพลตฟอร์มมีสิทธิระงับบัญชีชั่วคราวหรือถาวร

────────────────────────────────────────
หมวดที่ 11 : การร้องเรียน ข้อพิพาท และการพิจารณา
────────────────────────────────────────
11.1 เมื่อมีข้อร้องเรียนจากลูกค้า ผู้ให้บริการแพลตฟอร์มจะตรวจสอบหลักฐาน เช่น ภาพถ่าย ใบเสร็จ บันทึกแชท หรือรายงานแพทย์ (ถ้ามี)
11.2 หากพิสูจน์ได้ว่าข้อร้องเรียนมีเหตุผล ร้านค้าต้องคืนเงิน แก้ไข หรือชดเชยตามความเป็นธรรมและนโยบายของแพลตฟอร์ม
11.3 ร้านค้าต้องให้ความร่วมมือในการสอบสวน ไม่ปกปิด ไม่ทำลายหลักฐาน และตอบสอบถามภายในระยะเวลาที่กำหนด
11.4 การตัดสินของผู้ให้บริการแพลตฟอร์มในเรื่องข้อร้องเรียนเป็นไปเพื่อรักษาลำดับของแพลตฟอร์ม โดยไม่ตัดสิทธิร้านค้าในการโต้แย้งด้วยหลักฐาน

────────────────────────────────────────
หมวดที่ 12 : การตรวจสอบ ควบคุมคุณภาพ และการปฏิบัติตาม
────────────────────────────────────────
12.1 ผู้ให้บริการแพลตฟอร์มมีสิทธิสุ่มตรวจ ขอข้อมูล หรือตรวจสอบสินค้า สถานที่ หรือกระบวนการของร้านค้า เพื่อรักษามาตรฐาน
12.2 หากพบความผิดปกติ ผู้ให้บริการแพลตฟอร์มมีสิทธิสั่งระงับการขายชั่วคราว จนกว่าร้านค้าจะแก้ไขให้ถูกต้อง
12.3 ร้านค้าควรเข้าร่วมการอบรมหรือแนวปฏิบัติด้านสุขาภิบาล/ความปลอดภัยที่แพลตฟอร์มจัดหรือแนะนำ (ถ้ามี)

────────────────────────────────────────
หมวดที่ 13 : ข้อมูลส่วนบุคคล ความลับ และ PDPA
────────────────────────────────────────
13.1 ร้านค้ายอมรับนโยบายความเป็นส่วนตัวของแพลตฟอร์ม และใช้ข้อมูลลูกค้าเฉพาะเพื่อการให้บริการตามออเดอร์
13.2 ห้ามนำข้อมูลลูกค้า ข้อมูลคำสั่งซื้อ หรือข้อมูลภายในของแพลตฟอร์มไปใช้นอกวัตถุประสงค์ ขาย หรือเปิดเผยโดยไม่ได้รับอนุญาต
13.3 ร้านค้าต้องรักษาความลับของข้อมูลทางการค้าและข้อมูลส่วนบุคคลตาม พ.ร.บ. คุ้มครองข้อมูลส่วนบุคคล

